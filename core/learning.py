def build_poem(call_ai, now, slot, seen_urls=None):
    title, author, dynasty = POEMS[_slot_index(now, slot) % len(POEMS)]
    prompt = f"""请为下面这首古诗词写一份"每日诗词"推送。

诗词：《{title}》，{dynasty}代 {author}

严格按下面的格式输出，用【】标记分段，不要写多余的开场白，不要用 Markdown：

【原文】
完整原文，每一句之间用 " / " 隔开（不要换行）。原文必须和传世的通行版本逐字一致；
如果你对某些字句没有把握，就只写你确定的部分，宁可少写，不要写错或编造。
【赏析】
80-120字，用大白话讲清楚这首诗写了什么、好在哪里、读的时候该注意哪一句。不要用比喻拟人排比等修辞，不要说教。
【背景】
40-60字，讲创作背景、典故或一个有意思的小知识，必须是确凿的史实，不确定就写这首诗的体裁和格律特点。
"""
    text = call_ai(prompt)
    s = _sections(text, ["原文", "赏析", "背景"])
    if not s["原文"]:
        return ""
    return f"{title}|||{author}·{dynasty}|||{s['原文']}|||{s['赏析']}|||{s['背景']}"


# ---------------------------------------------------------------------------
# 历史上的今天（维基百科）
# 输出若干行：维基百科|||标题|||链接|||年份|||解读|||为什么值得知道
# ---------------------------------------------------------------------------
def _fetch_on_this_day(month, day):
    url = f"https://zh.wikipedia.org/api/rest_v1/feed/onthisday/events/{month:02d}/{day:02d}"
    r = requests.get(url, timeout=WIKI_TIMEOUT, headers=WIKI_HEADERS)
    r.raise_for_status()
    events = []
    for e in r.json().get("events", []):
        pages = e.get("pages") or []
        link = ""
        if pages:
            link = (pages[0].get("content_urls", {}).get("desktop", {}) or {}).get("page", "")
        if e.get("text") and link:
            events.append({"year": e.get("year"), "text": e["text"], "url": link})
    return events


def build_history(call_ai, now, slot, seen_urls=None, count=2):
    seen_urls = seen_urls or set()
    events = [e for e in _fetch_on_this_day(now.month, now.day) if e["url"] not in seen_urls]
    # 偏好有历史分量的老条目：按年份从早到晚取，避免全是近几年的新闻性事件
    events.sort(key=lambda e: (e["year"] is None, e["year"]))
    events = events[:30]
    if not events:
        return ""
    lines = "\n".join(f"{i + 1}. {e['year']}年：{e['text']}" for i, e in enumerate(events))
    prompt = f"""下面是"历史上的 {now.month} 月 {now.day} 日"发生过的事件（来自维基百科）。
请挑出 {count} 条最值得了解的：优先影响深远、能帮助理解世界今天为什么是这样的事件；
不要选纯娱乐、体育、灾难数字罗列这类内容。

{lines}

严格按下面的格式输出，每条一行，用 ||| 分隔四段，不要序号以外的前缀，不要写多余的开场白：
编号|||简体中文标题（15字以内）|||解读（70-110字：发生了什么、背景和影响，只能依据上面给的条目和公认的史实，不确定的细节、数字不要写）|||为什么值得知道（25-40字，说它和今天的联系）

不要用比喻拟人排比等修辞。
"""
    text = call_ai(prompt)
    out = []
    for line in text.split("\n"):
        parts = [p.strip() for p in line.split("|||")]
        if len(parts) < 4:
            continue
        num = re.sub(r"\D", "", parts[0])
        if not num or not (1 <= int(num) <= len(events)):
            continue
        ev = events[int(num) - 1]
        out.append(f"维基百科|||{_clean(parts[1])}|||{ev['url']}|||{ev['year']}年|||{_clean(parts[2])}|||{_clean(parts[3])}")
    return "\n".join(out[:count])


