def _wiki_summary(wiki_title):
    url = f"https://zh.wikipedia.org/api/rest_v1/page/summary/{quote(wiki_title)}"
    r = requests.get(url, timeout=WIKI_TIMEOUT, headers=WIKI_HEADERS)
    r.raise_for_status()
    j = r.json()
    return j.get("extract", ""), (j.get("content_urls", {}).get("desktop", {}) or {}).get("page", "")


