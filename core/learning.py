def _slot_index(now, slot):
    """午间/晚间不同的轮换序号：按日期递增，同一天内午间和晚间错开"""
    return now.date().toordinal() * 2 + (1 if slot == "evening" else 0)


def _clean(text):
    """去掉会破坏行格式的字符"""
    return re.sub(r"\s+", " ", (text or "").replace("|||", " ")).strip()


def _sections(text, markers):
    """按【标记】把 AI 返回的文本切成字典；缺少的标记返回空串"""
    out = {}
    for i, m in enumerate(markers):
        pat = re.escape(f"【{m}】")
        nxt = "|".join(re.escape(f"【{x}】") for x in markers[i + 1:]) or r"\Z"
        mt = re.search(pat + r"\s*(.*?)\s*(?=" + nxt + r"|\Z)", text, re.S)
        out[m] = _clean(mt.group(1)) if mt else ""
    return out


